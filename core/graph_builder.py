"""Builds a runnable flow function directly from a dashboard graph -- no .py
round-trip needed. Used by the dashboard's live-run websocket and the
assistant; the .py file generated by core.codegen is a separate, equivalent
artifact for the plain CLI runner."""

from dataclasses import asdict
import json
import re
from typing import Any, Callable

from flows.sdk import (Call, Check, FlowContext, StepFailed, StepReport,
                       expect_json, expect_persistence, expect_status)
from core.refs import eval_condition, eval_resolved, resolve_value


def _tool_from_name(api: Any, tool_name: str) -> Callable:
    tag, _, op_id = tool_name.partition("__")
    try:
        return getattr(getattr(api, tag), op_id)
    except AttributeError:
        raise ValueError(f"Unknown tool: {tool_name!r}")


def _build_check(node: dict, api: Any = None) -> Check:
    check_type = node["check_type"]
    if check_type == "status":
        check = expect_status(node["status"])
    elif check_type in ("json", "json_path"):
        kwargs: dict = {}
        if "not_none" in node:
            kwargs["not_none"] = node["not_none"]
        if "equals" in node:
            # Resolve lazily so comparisons such as response.id ==
            # $ctx.create.body.id use the values from this run, not literals.
            kwargs["equals"] = resolve_value(node["equals"])
        if "contains" in node:
            kwargs["equals"] = resolve_value(node["contains"])
            kwargs["op"] = "contains"
        if "op" in node:
            kwargs["op"] = node["op"]
        check = expect_json(node["path"], **kwargs)
    elif check_type == "persistence":
        tool_name = node.get("tool")
        if not tool_name:
            raise ValueError("persistence check requires a testing/state tool")
        kwargs: dict = {
            "status": node.get("status", 200),
            "path": node.get("path", ""),
            "not_none": node.get("not_none", False),
            "op": node.get("op", "=="),
        }
        if "equals" in node:
            kwargs["equals"] = resolve_value(node["equals"])
        check = expect_persistence(
            lambda _ctx: _tool_from_name(api, tool_name),
            resolve_value(node.get("args", {})),
            **kwargs,
        )
    else:
        raise ValueError(f"Unknown check_type: {check_type!r}")
    check.id = node.get("id")
    return check


def _build_validator(node: dict, api: Any):
    if node["kind"] == "check":
        return _build_check(node, api)
    if node["kind"] == "call":
        return _build_call(node, api)
    raise ValueError(f"Unknown node kind: {node['kind']!r}")


def _build_call(node: dict, api: Any) -> Call:
    raw_args = node.get("args", {})
    args = resolve_value(raw_args) if isinstance(raw_args, dict) else {}
    validate = [_build_validator(v, api) for v in node.get("validate", [])]
    return Call(
        tool=_tool_from_name(api, node["tool"]),
        args=args,
        bind_as=node.get("bind_as") or None,
        name=node.get("bind_as") or node["tool"],
        validate=validate,
        id=node.get("id"),
    )


def _evaluate_condition(node: dict, ctx: Any) -> tuple[bool, str]:
    left_ref = node.get("left", "")
    op = node.get("op", "==")
    right_val = node.get("right", "")

    left_fn = resolve_value(left_ref)
    left_val = eval_resolved(left_fn, ctx)

    right_fn = resolve_value(right_val)
    resolved_right = eval_resolved(right_fn, ctx)

    result = eval_condition(left_val, op, resolved_right)
    branch_name = "TRUE (THEN)" if result else "FALSE (ELSE)"
    desc = f"if {left_ref} {op} {right_val!r} -> {branch_name}"
    return result, desc


def _append_report(ctx: Any, report: StepReport) -> None:
    ctx.steps.append(report)
    if getattr(ctx, "_on_step", None):
        ctx._on_step(report)


def _run_with_retry(step: dict, ctx: Any, api: Any, call_stack: list[str]) -> None:
    """Retry an arbitrary graph step without leaking failed attempts as flow steps."""
    policy = step.get("retry") or {}
    attempts = max(1, int(policy.get("attempts", step.get("attempts", 3))))
    delay = max(0.0, float(policy.get("initial_delay_s", policy.get("delay_s", 0.25))))
    backoff = max(1.0, float(policy.get("backoff", 2)))
    max_delay = max(0.0, float(policy.get("max_delay_s", 5)))
    children: list[StepReport] = []
    last_error = None
    for attempt in range(1, attempts + 1):
        start = len(ctx.steps)
        bound_before = dict(ctx._bound)
        plain_step = {k: v for k, v in step.items() if k not in {"retry", "attempts"}}
        try:
            _run_step(plain_step, ctx, api, call_stack, _allow_retry=False)
            children.extend(ctx.steps[start:])
            del ctx.steps[start:]
            _append_report(ctx, StepReport(kind="retry", name=f"retry: {step.get('name') or step.get('tool') or step.get('kind')} ({attempt}/{attempts})", status="pass", children=children, id=step.get("id")))
            return
        except StepFailed as exc:
            children.extend(ctx.steps[start:])
            del ctx.steps[start:]
            ctx._bound = bound_before
            last_error = exc.report.error or exc.report.name
            if attempt < attempts and delay:
                ctx.wait(delay, name="retry backoff")
            delay = min(max_delay, delay * backoff) if max_delay else delay * backoff
    report = StepReport(kind="retry", name=f"retry: {step.get('name') or step.get('tool') or step.get('kind')}", status="fail", error=f"failed after {attempts} attempts: {last_error}", children=children, id=step.get("id"))
    _append_report(ctx, report)
    raise StepFailed(report)


def _run_step(step: dict, ctx: Any, api: Any, call_stack: list[str] | None = None, _allow_retry: bool = True) -> None:
    if call_stack is None:
        call_stack = []
    kind = step.get("kind", "call")
    if _allow_retry and step.get("retry") and kind != "retry":
        return _run_with_retry(step, ctx, api, call_stack)
    if kind == "call":
        ctx.run(_build_call(step, api))
    elif kind == "condition":
        try:
            result, desc = _evaluate_condition(step, ctx)
        except Exception as exc:
            report = StepReport(
                kind="condition",
                name=f"condition {step.get('left')} {step.get('op')}",
                status="fail",
                error=f"evaluation error: {exc}",
                id=step.get("id"),
            )
            _append_report(ctx, report)
            raise StepFailed(report)

        report = StepReport(
            kind="condition",
            name=desc,
            status="pass" if not (step.get("assert") is True and not result) else "fail",
            error=(f"assertion failed: expected {step.get('left')} {step.get('op', '==')} {step.get('right')!r}"
                   if step.get("assert") is True and not result else None),
            id=step.get("id"),
        )
        _append_report(ctx, report)

        if step.get("assert") is True and not result:
            raise StepFailed(report)

        branch = step.get("then_steps", []) if result else step.get("else_steps", [])
        for sub_step in branch:
            _run_step(sub_step, ctx, api, call_stack)
    elif kind == "flow":
        subflow_name = step.get("flow_name")
        if not subflow_name:
            raise ValueError("Flow step missing 'flow_name'")
        if subflow_name in call_stack:
            cycle_desc = " -> ".join(call_stack + [subflow_name])
            report = StepReport(
                kind="flow",
                name=f"flow: {subflow_name}",
                status="fail",
                error=f"Circular subflow detected: {cycle_desc}",
                id=step.get("id"),
            )
            _append_report(ctx, report)
            raise StepFailed(report)

        from core import flow_store
        sub_graph = flow_store.load_flow(subflow_name)

        def _subflow_fn(c):
            c.data.update(sub_graph.get("data", {}))
            for s in sub_graph.get("steps", []):
                _run_step(s, c, api, call_stack + [subflow_name])

        _subflow_fn.__flow_name__ = subflow_name
        ctx.run_flow(_subflow_fn, id=step.get("id"), bind_as=step.get("bind_as"))
    elif kind == "split":
        mode = step.get("mode", "parallel")
        name = step.get("name") or f"Split ({mode})"
        branches_data = step.get("branches", [])
        branch_tuples = []
        for idx, b in enumerate(branches_data):
            b_name = b.get("name") or f"Branch {idx + 1}"
            b_steps = b.get("steps", [])

            def make_branch_fn(steps_to_run):
                def _fn(c):
                    for s in steps_to_run:
                        _run_step(s, c, api, call_stack)
                return _fn

            branch_tuples.append((b_name, make_branch_fn(b_steps)))
        ctx.run_split(branch_tuples, mode=mode, id=step.get("id"), name=name)
    elif kind == "wait":
        ctx.wait(step.get("seconds", step.get("duration_s", 1)), name=step.get("name", "wait"), id=step.get("id"))
    elif kind == "retry":
        wrapped = {**step, "kind": step.get("target_kind", "sequence")}
        if wrapped["kind"] == "sequence":
            # A retry block retries all contained steps as one transaction-like unit.
            wrapped["kind"] = "condition"  # replaced below; avoids recursive retry handling
            def run_sequence():
                for sub_step in step.get("steps", []):
                    _run_step(sub_step, ctx, api, call_stack)
            policy_step = {**step, "kind": "retry_sequence", "name": step.get("name", "retry block")}
            # Inline version of _run_with_retry because the target is a list.
            attempts = max(1, int(step.get("attempts", 3)))
            delay = max(0.0, float(step.get("initial_delay_s", 0.25)))
            backoff = max(1.0, float(step.get("backoff", 2)))
            children, last_error = [], None
            for attempt in range(1, attempts + 1):
                start, bound_before = len(ctx.steps), dict(ctx._bound)
                try:
                    run_sequence()
                    children.extend(ctx.steps[start:]); del ctx.steps[start:]
                    _append_report(ctx, StepReport(kind="retry", name=f"retry: {policy_step['name']} ({attempt}/{attempts})", status="pass", children=children, id=step.get("id")))
                    return
                except StepFailed as exc:
                    children.extend(ctx.steps[start:]); del ctx.steps[start:]; ctx._bound = bound_before
                    last_error = exc.report.error or exc.report.name
                    if attempt < attempts and delay: ctx.wait(delay, name="retry backoff")
                    delay *= backoff
            report = StepReport(kind="retry", name=f"retry: {policy_step['name']}", status="fail", error=f"failed after {attempts} attempts: {last_error}", children=children, id=step.get("id"))
            _append_report(ctx, report); raise StepFailed(report)
        _run_with_retry(wrapped, ctx, api, call_stack)
    elif kind == "wait_until":
        timeout = max(0.0, float(step.get("timeout_s", 30)))
        interval = max(0.01, float(step.get("interval_s", 1)))
        backoff = max(1.0, float(step.get("backoff", 1)))
        max_interval = max(interval, float(step.get("max_interval_s", interval)))
        import time
        started = time.monotonic()
        while True:
            for sub_step in step.get("steps", []):
                _run_step(sub_step, ctx, api, call_stack)
            result, desc = _evaluate_condition(step, ctx)
            if result:
                _append_report(ctx, StepReport(kind="wait_until", name=f"wait_until: {desc}", status="pass", id=step.get("id")))
                return
            if time.monotonic() - started >= timeout:
                report = StepReport(kind="wait_until", name=f"wait_until: {desc}", status="fail", error=f"timed out after {timeout:g}s", id=step.get("id"))
                _append_report(ctx, report); raise StepFailed(report)
            ctx.wait(interval, name="wait_until poll")
            interval = min(max_interval, interval * backoff)
    else:
        raise ValueError(f"Unknown step kind: {kind!r}")


_flow_sessions: dict[str, dict[str, Any]] = {}


def get_flow_session(flow_name: str) -> dict[str, Any]:
    return _flow_sessions.setdefault(flow_name, {})


def clear_flow_session(flow_name: str) -> None:
    _flow_sessions.pop(flow_name, None)


def make_flow_fn(graph: dict, workspace: dict | None = None) -> Callable:
    """Turns a saved graph into a callable usable with runner.executor.run_flow."""

    def flow_fn(ctx):
        if workspace:
            if hasattr(ctx, "workspace_data") and not ctx.workspace_data:
                ctx.workspace_data.update(workspace.get("data", {}))
            if hasattr(ctx, "secrets") and not ctx.secrets:
                ctx.secrets.update(workspace.get("secrets", {}))
            for k, v in workspace.get("data", {}).items():
                if k not in ctx.data:
                    ctx.data[k] = v
        ctx.data.update(graph.get("data", {}))
        primary_error = None
        try:
            for step in graph["steps"]:
                _run_step(step, ctx, ctx.api)
        except BaseException as exc:
            primary_error = exc
        finally:
            # Cleanup is intentionally independent of normal success.  Do not
            # mask the failure that triggered it with a secondary teardown error.
            for cleanup_step in graph.get("finally_steps", graph.get("teardown_steps", [])):
                try:
                    _run_step(cleanup_step, ctx, ctx.api)
                except StepFailed:
                    if primary_error is None:
                        raise
        if primary_error is not None:
            raise primary_error
        flow_name = graph.get("name")
        if flow_name:
            _flow_sessions[flow_name] = dict(ctx._bound)

    flow_fn.__flow_name__ = graph["name"]
    flow_fn.__is_flow__ = True
    return flow_fn


def _find_node_and_prereqs(steps: list[dict], node_id: str, accumulated_prereqs: list[dict] | None = None) -> tuple[dict | None, list[dict]]:
    if accumulated_prereqs is None:
        accumulated_prereqs = []

    for step in steps:
        if step.get("id") == node_id:
            return step, list(accumulated_prereqs)

        for v in step.get("validate", []):
            if v.get("id") == node_id:
                return v, list(accumulated_prereqs) + [step]

        then_steps = step.get("then_steps", [])
        if then_steps:
            found, p = _find_node_and_prereqs(then_steps, node_id, list(accumulated_prereqs) + [step])
            if found:
                return found, p
        else_steps = step.get("else_steps", [])
        if else_steps:
            found, p = _find_node_and_prereqs(else_steps, node_id, list(accumulated_prereqs) + [step])
            if found:
                return found, p

        for b in step.get("branches", []):
            b_steps = b.get("steps", [])
            if b_steps:
                found, p = _find_node_and_prereqs(b_steps, node_id, list(accumulated_prereqs) + [step])
                if found:
                    return found, p

        accumulated_prereqs.append(step)
    return None, []


def get_node_ctx_deps(node: dict) -> set[str]:
    serialized = json.dumps(node)
    return set(re.findall(r"\$ctx\.([a-zA-Z0-9_]+)", serialized))


def run_single_node(graph: dict, node_id: str, api: Any, workspace: dict | None = None) -> dict:
    """Runs a single node in a flow graph, auto-resolving prerequisite steps if needed."""
    flow_name = graph.get("name", "temp_flow")
    session_bound = _flow_sessions.get(flow_name, {})

    target_node, prereqs = _find_node_and_prereqs(graph.get("steps", []), node_id)
    if not target_node:
        raise ValueError(f"Node not found in graph: {node_id}")

    ws_data = workspace.get("data", {}) if workspace else {}
    ws_secrets = workspace.get("secrets", {}) if workspace else {}
    ctx = FlowContext(
        api,
        data=graph.get("data", {}),
        bound=session_bound,
        workspace_data=ws_data,
        secrets=ws_secrets,
    )

    # Check if any dependencies are missing from ctx._bound
    deps = get_node_ctx_deps(target_node)
    missing_deps = deps - set(ctx._bound.keys())

    if missing_deps:
        for prereq in prereqs:
            try:
                _run_step(prereq, ctx, api)
            except StepFailed as sf:
                return {
                    "ok": False,
                    "status": "fail",
                    "name": target_node.get("tool") or target_node.get("name", "step"),
                    "id": target_node.get("id"),
                    "prereq_failed": asdict(sf.report),
                    "error": f"Prerequisite step '{sf.report.name}' failed before reaching this node: {sf.report.error}",
                }

    kind = target_node.get("kind", "call")
    report = None
    if kind == "call":
        call = _build_call(target_node, api)
        report = ctx._execute_call(call)
        ctx.steps.append(report)
        if target_node.get("bind_as"):
            ctx._bound[target_node["bind_as"]] = ctx._bound.get(target_node["bind_as"])
    elif kind == "check":
        check = _build_check(target_node)
        parent_call = prereqs[-1] if prereqs else None
        parent_result = None
        if parent_call and parent_call.get("bind_as"):
            parent_result = ctx._bound.get(parent_call["bind_as"])
        report = check.evaluate(parent_result, ctx)
        ctx.steps.append(report)
    elif kind == "condition":
        try:
            result, desc = _evaluate_condition(target_node, ctx)
            report = StepReport(kind="condition", name=desc, status="pass", id=target_node.get("id"))
        except Exception as exc:
            report = StepReport(
                kind="condition",
                name=f"condition {target_node.get('left')} {target_node.get('op')}",
                status="fail",
                error=str(exc),
                id=target_node.get("id"),
            )
        ctx.steps.append(report)
    elif kind == "flow":
        try:
            _run_step(target_node, ctx, api)
            report = ctx.steps[-1]
        except StepFailed as sf:
            report = sf.report
        except Exception as exc:
            report = StepReport(
                kind="flow",
                name=f"flow: {target_node.get('flow_name')}",
                status="fail",
                error=str(exc),
                id=target_node.get("id"),
            )
            ctx.steps.append(report)
    elif kind == "split":
        try:
            _run_step(target_node, ctx, api)
            report = ctx.steps[-1]
        except StepFailed as sf:
            report = sf.report
        except Exception as exc:
            report = StepReport(
                kind="split",
                name=f"split: {target_node.get('name', 'Split')}",
                status="fail",
                error=str(exc),
                id=target_node.get("id"),
            )
            ctx.steps.append(report)
    else:
        raise ValueError(f"Unknown node kind: {kind}")

    session_bound.update(ctx._bound)
    _flow_sessions[flow_name] = session_bound

    return {
        "ok": report.status == "pass",
        "status": report.status,
        "name": report.name,
        "id": target_node.get("id"),
        "report": asdict(report),
        "response": getattr(report, "response", None),
        "error": report.error,
    }
